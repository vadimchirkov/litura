import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ChangeSet } from '@codemirror/state';
import { documentStore } from '../document-store.js';
import { createSession } from '../live-session.js';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'stilura-work-'));
const file = path.join(directory, 'draft.md');
fs.writeFileSync(file, 'Opening.\n\nTarget phrase.\n\nClosing.');
let session = createSession(documentStore(file));
const read = () => session.read();
const note = () => read().notes[0];
const action = (type, extra = {}) => session.work({ type, id: 'task', generation: note().work.generation, ...extra });
try {
  const original = read();
  assert.throws(() => session.finishWork({ id: 'task' }), /claim token/);
  session.updateNotes({ epoch: original.epoch, version: original.version, operations: [{ type: 'put', id: 'task', note: {
    text: 'Clarify this.', quote: 'Target phrase', para: 1, off: 0, length: 13, anchor: 'Target phrase.' } }] });
  assert.equal(note().work.status, 'queued');
  const job = session.claimWork('agent-a');
  assert.equal(job.target.text, 'Target phrase');
  assert.equal(session.claimWork('agent-b'), null, 'Two agents must not claim the same note');
  assert.equal(session.claimWork('agent-a').token, job.token, 'A lost claim acknowledgement must be retryable');
  session.patch([{ old: 'Opening.', new: 'New.\n\nOpening.' }], job.revision);
  session.finishWork({ id: 'task', token: job.token, revision: job.revision, edits: [{ old: 'Target phrase', new: 'Clear passage' }], comment: 'Made it concrete.' });
  assert.equal(note().work.status, 'review');
  assert.equal(note().resolved, false, 'Applied is not accepted');
  assert(read().text.includes('Clear passage'));
  const result = note().work.attempts.at(-1);
  action('revert', { attempt: result.id });
  assert.equal(read().text, 'New.\n\nOpening.\n\nTarget phrase.\n\nClosing.');
  assert.equal(note().work.status, 'reverted');
  assert.equal(session.claimWork('agent-a'), null, 'Undo must not immediately rerun the task');
  action('regenerate');
  const retry = session.claimWork('agent-a');
  session.finishWork({ id: 'task', token: retry.token, revision: retry.revision, edits: [{ old: 'Target phrase', new: 'Another version' }] });
  const latest = note().work.attempts.at(-1);
  action('accept', { attempt: latest.id });
  assert.equal(note().work.status, 'done');
  assert.equal(note().resolved, true);
  session.patch([{ old: 'New.', new: 'Above.\n\nNew.' }], read().revision);
  action('revert', { attempt: latest.id });
  assert.equal(note().anchor, 'Target phrase.');
  assert.equal(note().para, 3, 'Undo of completed work must restore its anchor after insertions above');
  action('regenerate');
  const acceptedAgain = session.claimWork('agent-a');
  session.finishWork({ id: 'task', token: acceptedAgain.token, revision: acceptedAgain.revision, edits: [{ old: 'Target phrase', new: 'Another version' }] });
  action('accept', { attempt: note().work.attempts.at(-1).id });
  action('comment', { text: 'Shorter, please.' });
  assert.equal(note().work.status, 'queued');
  assert.equal(note().resolved, false);
  const followup = session.claimWork('agent-b');
  assert.equal(followup.messages.at(-1).text, 'Shorter, please.');
  const before = read();
  session.patch([{ old: 'Another version', new: 'Human wording' }], before.revision);
  assert.throws(() => session.finishWork({ id: 'task', token: followup.token, revision: followup.revision, edits: [{ old: 'Another version', new: 'Must not replace typing' }] }), /passage was edited/);
  assert.throws(() => action('revert', { attempt: note().work.attempts.at(-1).id }), /changed/);
  session.finishWork({ id: 'task', token: followup.token, error: 'Need clarification.' });
  assert.equal(note().work.status, 'blocked');
  assert.equal(session.claimWork('agent-c'), null);
  action('regenerate');
  const restarting = session.claimWork('agent-c');
  session.close(); session = createSession(documentStore(file));
  assert.equal(note().work.status, 'queued', 'Interrupted jobs are recoverable after a restart');
  assert.throws(() => session.finishWork({ id: 'task', token: restarting.token, revision: restarting.revision, edits: [] }), /claim/);
  assert.equal(note().work.messages.at(-1).text, 'Shorter, please.');
  console.log('Work checks passed: claiming, retries, status, tracked edits, safe revert, feedback, conflicts and restart.');
} finally { session.close(); fs.rmSync(directory, { recursive: true, force: true }); }
